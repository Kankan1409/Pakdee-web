import { DatabaseService } from "@/lib/database.service";
import { decodeSlipImage, savePaymentSlip, slipDatabase, SlipError } from "@/lib/payment-slips-server";
import { verifyWithSlip2Go } from "@/lib/slip2go";
import { toUuid } from "@/lib/supabase-relational";
import type { Invoice, BranchSettingsDetail } from "@/types/dormitory";

// The caller must authorize this property before invoking this server-only function.
export async function verifyStoredPayment(propertyId: string, id: string) {
  const db = slipDatabase();
  const { data: slip, error } = await db.from("payment_slips")
    .select("invoice_id,image_data,verification_status,invoices(invoice_number)")
    .eq("id", id).eq("property_id", toUuid(propertyId)).maybeSingle();
  if (error) throw new SlipError("โหลดสลิปสำหรับตรวจสอบไม่สำเร็จ", 503);
  if (!slip) throw new SlipError("ไม่พบสลิปในสาขานี้", 404);
  if (slip.verification_status === "passed") return { status: "passed", message: "สลิปนี้ถูกตรวจและรับชำระไว้แล้วครับ" };
  if (slip.verification_status === "rejected") return { status: "rejected", message: "สลิปนี้ถูกปฏิเสธแล้ว กรุณาส่งหลักฐานใหม่" };
  await DatabaseService.init();
  const linked = Array.isArray(slip.invoices) ? slip.invoices[0] : slip.invoices;
  const invoice = (await DatabaseService.getInvoices(propertyId)).find(i =>
    i.invoiceNumber === linked?.invoice_number && toUuid(i.id) === slip.invoice_id &&
    i.propertyId && toUuid(i.propertyId) === toUuid(propertyId));
  if (!invoice) throw new SlipError("ไม่พบบิลที่ตรงกับสลิปในสาขานี้", 404);
  if (!["unpaid", "overdue", "pending_review"].includes(invoice.status)) {
    return { status: "pending", message: "บิลนี้ไม่ได้อยู่ในสถานะรอรับชำระ จึงไม่ตรวจและตัดยอดซ้ำ" };
  }
  const property = await DatabaseService.getProperty(propertyId);
  const settings = await DatabaseService.getBranchSettings(property, propertyId);
  const result = await verifyLinePayment(propertyId, invoice, settings, decodeSlipImage(slip.image_data), "stored-slip");
  return { ...result, status: result.amount !== undefined ? "passed" : "pending" };
}

export async function verifyLinePayment(propertyId: string, invoice: Invoice, settings: BranchSettingsDetail,
  image: Buffer, filename: string): Promise<{ message: string; amount?: number }> {
  const id = await savePaymentSlip(propertyId, invoice.invoiceNumber, image, filename);
  const db = slipDatabase();
  const { data: slip, error } = await db.from("payment_slips").select("image_data,image_sha256,verification_status")
    .eq("id", id).eq("property_id", toUuid(propertyId)).single();
  if (error || !slip) throw new Error("Cannot read saved slip");
  if (slip.verification_status === "passed") return { message: "สลิปนี้ถูกตรวจและรับชำระไว้แล้วครับ" };
  const promptpay = settings.promptpayNumber?.replace(/\D/g, "") || "";
  // Slip2Go distinguishes mobile, national ID and wallet proxies from bank accounts.
  const receiverAccountType = promptpay.length === 10 ? "02001" :
    promptpay.length === 13 ? "02003" : promptpay.length === 15 ? "02004" : undefined;
  if (promptpay && !receiverAccountType) return { message: "รูปแบบเลขพร้อมเพย์ของสาขาไม่ถูกต้อง กรุณาให้เจ้าหน้าที่ตรวจสอบการตั้งค่าก่อนรับชำระ" };
  const result = await verifyWithSlip2Go(settings.slip2goSecretKey?.trim() || process.env.SLIP2GO_SECRET_KEY || "", {
    imageBuffer: decodeSlipImage(slip.image_data), expectedAmount: invoice.totalAmount,
    // Bills generated by this app use PromptPay QR; verify both PromptPay and Bank Account destinations.
    receiverAccount: settings.promptpayNumber?.trim() || settings.bankAccountNumber?.trim(),
    receiverAccountType,
  });
  if (!result.success) return { message: `${result.error}\n\nบิล ${invoice.invoiceNumber} ห้อง ${invoice.roomNumber}: ยังไม่ยืนยันการชำระเงินจากสลิปนี้ครับ` };
  const { data: duplicates, error: duplicateError } = await db.from("payment_slips").select("id")
    .eq("transaction_ref", result.transRef!).neq("id", id).limit(1);
  if (duplicateError) return { message: "⚠️ ตรวจประวัติสลิปไม่สำเร็จ ยังไม่รับชำระ กรุณาลองใหม่ภายหลัง" };
  if (duplicates?.length) return { message: "⚠️ ตรวจพบสลิปซ้ำ ธุรกรรมนี้มีอยู่ในระบบแล้ว จึงไม่รับชำระซ้ำครับ" };
  // No fallback to an invoice amount, guessed bank or manufactured reference.
  const latest = (await DatabaseService.getInvoices(propertyId)).find(i => i.id === invoice.id);
  if (!latest || !["unpaid", "overdue", "pending_review"].includes(latest.status) || latest.totalAmount !== result.amount) {
    return { message: "สถานะหรือยอดบิลเปลี่ยนไป กรุณาให้เจ้าหน้าที่ตรวจสอบก่อนรับชำระ" };
  }
  const updated = await DatabaseService.updateInvoiceStatus(invoice.id, "paid", result.amount!, {
    slipStatus: "passed", slipVerifiedAt: new Date().toISOString(), slipVerifiedBy: "ai",
    slipTransRef: result.transRef, slipBank: result.senderBank || result.receiverBank,
    slipHash: slip.image_sha256,
  });
  if (!updated) return { message: "Slip2Go ตรวจผ่าน แต่บันทึกรับชำระไม่สำเร็จ กรุณาติดต่อเจ้าหน้าที่" };
  const { error: auditError } = await db.from("payment_slips").update({ verification_status: "passed",
    verified_at: new Date().toISOString(), transaction_ref: result.transRef }).eq("id", id).eq("property_id", toUuid(propertyId));
  if (auditError) console.error("[SLIP2GO] Failed to persist slip audit status", { code: auditError.code });
  return { amount: result.amount, message: `✅ สลิปผ่านการตรวจสอบจาก Slip2Go\nบิล ${invoice.invoiceNumber} ห้อง ${invoice.roomNumber}\nรับชำระ ฿${result.amount!.toLocaleString()} แล้วครับ\nรหัสอ้างอิง: ${result.transRef}` };
}
